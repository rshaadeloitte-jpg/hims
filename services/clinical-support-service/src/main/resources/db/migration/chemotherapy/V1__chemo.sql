-- ============================================================================
-- V1 — ihms_chemotherapy schema (Chemotherapy service, M29)
-- Chemotherapy regimen cycle planning and oncology treatment administration.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS ihms_chemotherapy;

SET search_path TO ihms_chemotherapy, public;

CREATE TABLE IF NOT EXISTS ihms_chemotherapy.chemo_regimen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    patient_name VARCHAR(255),
    regimen_name VARCHAR(255) NOT NULL,
    protocol_code VARCHAR(100),
    diagnosis VARCHAR(255),
    current_cycle INT NOT NULL DEFAULT 1,
    total_cycles INT NOT NULL DEFAULT 1,
    cycle_interval_days INT,
    status VARCHAR(50) NOT NULL DEFAULT 'PLANNED',
    start_date DATE,
    end_date DATE,
    next_due_date DATE,
    prescribed_by VARCHAR(255),
    notes TEXT,
    unit_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_chemo_regimen_patient ON ihms_chemotherapy.chemo_regimen (patient_id);
CREATE INDEX IF NOT EXISTS ix_chemo_regimen_status ON ihms_chemotherapy.chemo_regimen (status);

CREATE TABLE IF NOT EXISTS ihms_chemotherapy.chemo_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    plan_name VARCHAR(255),
    start_date DATE,
    status VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS ihms_chemotherapy.chemo_regimen_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT,
    drug_name VARCHAR(255),
    dosage VARCHAR(50),
    unit VARCHAR(50),
    route VARCHAR(50),
    day INT
);

CREATE TABLE IF NOT EXISTS ihms_chemotherapy.chemo_cycle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT,
    cycle_number INT,
    start_date DATE,
    status VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS ihms_chemotherapy.tixml_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_name VARCHAR(100),
    template_json TEXT
);

CREATE TABLE IF NOT EXISTS ihms_chemotherapy.chemo_coversheet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT,
    current_cycle INT,
    lab_values TEXT,
    vitals TEXT
);
