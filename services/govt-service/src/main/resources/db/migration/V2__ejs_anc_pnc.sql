CREATE TABLE IF NOT EXISTS ihms_govt.t_ejs_asha_work (
    id BIGSERIAL PRIMARY KEY,
    beneficiary_id BIGINT,
    beneficiary_name VARCHAR(255),
    tracking_type VARCHAR(16) NOT NULL,
    visit_date VARCHAR(32),
    asha_id BIGINT,
    asha_name VARCHAR(255),
    status VARCHAR(32) DEFAULT 'SCHEDULED',
    gestational_week INTEGER,
    weight NUMERIC(6,2),
    bp_systolic INTEGER,
    bp_diastolic INTEGER,
    hemoglobin NUMERIC(6,2),
    immunization_given VARCHAR(255),
    delivery_date VARCHAR(32),
    delivery_type VARCHAR(32),
    postnatal_day INTEGER,
    child_age_months INTEGER,
    weight_child NUMERIC(6,2),
    height_child NUMERIC(6,2),
    immunization_status VARCHAR(32),
    nutrition_status VARCHAR(32),
    remarks TEXT,
    next_visit_date VARCHAR(32),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ihms_govt.t_ejs_geography (
    id BIGSERIAL PRIMARY KEY,
    asha_id BIGINT,
    asha_name VARCHAR(255),
    state VARCHAR(100),
    district VARCHAR(100),
    block VARCHAR(100),
    village VARCHAR(100),
    sub_center VARCHAR(100),
    total_population INTEGER DEFAULT 0,
    target_couples INTEGER DEFAULT 0,
    pregnant_women INTEGER DEFAULT 0,
    children_under5 INTEGER DEFAULT 0,
    households INTEGER DEFAULT 0,
    eligible_couples INTEGER DEFAULT 0,
    is_active BOOLEAN DEFAULT TRUE,
    last_enumeration_date VARCHAR(32),
    remarks TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);