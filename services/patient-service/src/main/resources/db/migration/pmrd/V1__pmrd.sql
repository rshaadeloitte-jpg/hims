CREATE SCHEMA IF NOT EXISTS ihms_pmrd;
SET search_path TO ihms_pmrd, public;

CREATE TABLE IF NOT EXISTS ihms_pmrd.pmrd_encounter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id BIGINT,
    patient_id BIGINT NOT NULL,
    visit_ien VARCHAR(50),
    patient_ien VARCHAR(50),
    unit_id BIGINT,
    date DATE,
    type VARCHAR(10),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ihms_pmrd.patient_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT,
    document_name VARCHAR(255),
    file_category VARCHAR(100),
    upload_date TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ihms_pmrd.jsy_form_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT,
    form_type VARCHAR(10),
    pcts_no VARCHAR(50),
    caste_id BIGINT,
    ration_card_number VARCHAR(100),
    bpl_number VARCHAR(100),
    res_city_id BIGINT
);
